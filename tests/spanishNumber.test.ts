import { describe, expect, it } from 'vitest';
import { parseSpanishNumber } from '@/lib/spanishNumber';

describe('parseSpanishNumber', () => {
  it.each([
    ['2500', 2500],
    ['2.500', 2500],
    ['2.500,50', 2500.5],
    ['2 500', 2500],
    ['2\u00a0500', 2500],
    ['2\u202f500', 2500],
    ['2.500,50 €', 2500.5],
    ['EUR 2.500,50', 2500.5],
    ['$2,500.50', 2500.5],
    ['2,5', 2.5],
    ['1,005', 1.005],
    ['1.005', 1005],
    ['1.234,56', 1234.56],
    ['1,234.56', 1234.56],
    ['1.234.567,89', 1234567.89],
    ['1,234,567.89', 1234567.89],
    ['1.234.567', 1234567],
    ['1,234,567', 1234567],
    ['12 345 678,90', 12345678.9],
    ['2 500.50', 2500.5],
    ['−2.500,50 €', -2500.5],
    ['-€ 2.500,50', -2500.5],
    ['EUR -2.500,50', -2500.5],
    ['+2 500,5 EUR', 2500.5],
    ['15,5 %', 15.5],
    ['\n 2.500,50 € \r\n', 2500.5],
    ['.5', 0.5],
    [',5', 0.5],
    ['12,', 12],
    ['12.', 12],
  ])('parses %s as %d', (value, expected) => {
    expect(parseSpanishNumber(value)).toBe(expected);
  });

  it.each(['', 'EUR', 'importe 2500', '2.500,50 euros'])('rejects %s', (value) => {
    expect(parseSpanishNumber(value)).toBeNaN();
  });

  it.each([
    '1,,50', '1,2,3', '1..800', '1.00.000', '12.34,56', '12,34.56',
    '1.234,5,6', '1,234.5.6', '1.234.56', '1,234,56', '1..', '1,,',
    '1,50\n2,50', '12\t34', '100\r\n200', '100 € 200', '15%5',
    '12 34', '1 23 456', '1. 234', '1, 50', '1 234.567,89',
  ])('rejects malformed separators or multiple copied cells: %j', (value) => {
    expect(parseSpanishNumber(value)).toBeNaN();
  });
});
